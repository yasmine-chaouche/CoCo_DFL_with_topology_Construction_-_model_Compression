"""Sparsification operators (Section 2.2).

A compressor returns the 0/1 mask z_i (Eq. 6) for worker i's model. With RandomK
the mask is regenerated by neighbours from a random seed, so only the selected
values (+ the seed) are transmitted.
"""
import torch


def random_k_mask(x, ratio, seed):
    if ratio >= 1.0:
        return torch.ones_like(x, dtype=torch.bool)
    k = max(1, int(round(ratio * x.numel())))
    g = torch.Generator(device=x.device)
    g.manual_seed(int(seed))
    # k distinct random indices: smallest-k of i.i.d. uniform scores
    scores = torch.rand(x.numel(), device=x.device, generator=g)
    idx = torch.topk(scores, k, largest=False, sorted=False).indices
    mask = torch.zeros_like(x, dtype=torch.bool)
    mask[idx] = True
    return mask


def top_k_mask(x, ratio, seed=None):
    if ratio >= 1.0:
        return torch.ones_like(x, dtype=torch.bool)
    k = max(1, int(round(ratio * x.numel())))
    idx = torch.topk(x.abs(), k, sorted=False).indices
    mask = torch.zeros_like(x, dtype=torch.bool)
    mask[idx] = True
    return mask


COMPRESSORS = {"randomk": random_k_mask, "topk": top_k_mask}
